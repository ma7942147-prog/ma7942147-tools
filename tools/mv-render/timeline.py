def build_lines():
    """把每個段落依權重切成句子時間軸。"""
    out = []
    for s, e, lines in SECTIONS:
        total_w = sum(w for w, _ in lines)
        span = e - s
        cur = s
        for w, text in lines:
            d = span * w / total_w
            start = cur + LAG
            end = cur + d + LAG - GAP
            out.append((start, end, text))
            cur += d
    return out


