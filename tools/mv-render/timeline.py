def _weight(line):
    """依字數估算一句要唱多久（英文字母算半個字）。"""
    n = sum(0.5 if c.isascii() and c.isalnum() else (0 if c == " " else 1)
            for c in line)
    return max(n, 4.0)


def build_lines():
    """產生 (start, end, text)。起唱點量得到就用量到的，量不到才分配。"""
    out = []
    for sec in SECTIONS:
        name, onsets, span_start, end, lines = sec
        if onsets is None:
            w = [_weight(t) for t in lines]
            total = sum(w)
            onsets = []
            cur = span_start
            for x in w:
                onsets.append(cur)
                cur += (end - span_start) * x / total
        starts = list(onsets) + [end]
        for i, text in enumerate(lines):
            out.append((starts[i] + LAG, starts[i + 1] + LAG - GAP, text))
    return out


